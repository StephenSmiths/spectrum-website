export function publishedShowcases() {
  return showcases.filter((s) => s.status === "published");
}

export function featuredShowcases() {
  return publishedShowcases().filter((s) => s.featured);
}

export function getShowcase(slug: string) {
  return publishedShowcases().find((s) => s.slug === slug);
}

export function showcasesByCategory(category: ShowcaseCategory | "all") {
  const list = publishedShowcases();
  if (category === "all") return list;
  return list.filter((s) => s.category === category);
}

